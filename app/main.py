def _assert_patient_access(current_user: models.User, patient: models.Patient):
    """Row-level ownership check: a patient may only access their own
    record; clinicians/admins may access any patient."""
    if current_user.role == models.UserRole.patient and str(patient.user_id) != str(current_user.id):
        raise HTTPException(status_code=403, detail="You do not have access to this patient's records.")


