@app.get("/notifications", response_model=list[alert_schemas.NotificationResponse], tags=["Alerts"])
def list_my_notifications(db: Session = Depends(get_db), current_user: models.User = Depends(get_current_user)):
    from sqlalchemy import select as _select

    stmt = (
        _select(Notification)
        .where(Notification.user_id == current_user.id)
        .order_by(Notification.created_at.desc())
    )
    return db.execute(stmt).scalars().all()
