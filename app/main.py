@app.post(
    "/patients/{patient_id}/thresholds", response_model=alert_schemas.ThresholdResponse,
    status_code=201, tags=["Alerts"],
)
def create_threshold(
    patient_id: UUID, payload: alert_schemas.ThresholdCreateRequest, db: Session = Depends(get_db),
    current_user: models.User = Depends(get_current_user),
):
    """Create a patient-specific threshold override. Patient-specific
    thresholds take priority over the global defaults for that patient +
    vital_type combination (see app/alert_rules.evaluate_vital_threshold)."""
    patient = crud.get_patient(db, patient_id)
    _assert_patient_access(current_user, patient)

    threshold = VitalThreshold(
        patient_id=str(patient_id), vital_type=payload.vital_type, severity=payload.severity,
        min_value=payload.min_value, max_value=payload.max_value, is_active=True,
    )
    db.add(threshold)
    db.commit()
    db.refresh(threshold)
    return threshold


