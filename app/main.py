@app.post("/auth/register", response_model=schemas.UserOut, status_code=201, tags=["Auth"])
def register(payload: schemas.UserCreate, db: Session = Depends(get_db)):
    """Create a new user account. In production, self-registration would
    typically be restricted to the 'patient' role, with clinician/admin
    accounts provisioned by an administrator; left open here for testing."""
    existing = crud.get_user_by_email(db, payload.email)
    if existing:
        raise crud.DuplicateError(f"A user with email '{payload.email}' already exists.")
    user = crud.create_user(
        db, email=payload.email, hashed_password=hash_password(payload.password), role=payload.role
    )
    return user


@app.post("/auth/login", response_model=schemas.Token, tags=["Auth"])
def login(payload: schemas.LoginRequest, db: Session = Depends(get_db)):
    user = crud.get_user_by_email(db, payload.email)
    if not user or not verify_password(payload.password, user.hashed_password):
        access_logger.warning(f"Failed login attempt for {payload.email}")
        raise HTTPException(status_code=401, detail="Incorrect email or password.")
    if not user.is_active:
        raise HTTPException(status_code=403, detail="This account has been deactivated.")
    token, expires_in = create_access_token(str(user.id), user.role.value)
    access_logger.info(f"Successful login: {user.email}")
    return schemas.Token(access_token=token, expires_in=expires_in)


